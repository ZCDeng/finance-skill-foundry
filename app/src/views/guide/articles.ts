/**
 * The 使用指南 articles. Each one says what the product does today, in the words its
 * screens use, and where on screen to do it. Nothing here makes a financial judgement
 * for the reader, and nothing claims a check the software does not run.
 */

import type { AskId } from './ask.js';

export type GuideTarget = 'datasets' | 'scope' | 'structure' | 'billing' | 'results' | 'operations' | 'dashboard' | 'drafts' | 'workbook' | 'close';

export type GuideBlock =
  | { kind: 'p'; text: string }
  | { kind: 'steps'; items: string[] }
  | { kind: 'list'; items: string[] }
  | { kind: 'legend' }
  /** The six quick-start steps, read from the open task's own state. */
  | { kind: 'checklist' }
  /** First run: practise on the synthetic task, or start with your own files. */
  | { kind: 'start' }
  | { kind: 'open'; target: GuideTarget; label: string }
  /** Put a question into the conversation; it is never sent from here. */
  | { kind: 'ask'; ask: AskId; label: string }
  /** 你应该看到: the figures this step of the example route ends on (held to demo_pack/expected.json by a test). */
  | { kind: 'expect'; items: string[] }
  /** Open the example's reference task at the same page, to compare. */
  | { kind: 'reference'; target: GuideTarget; label: string }
  /** Make the September practice task, for the route's last step. */
  | { kind: 'next-month' }
  /**
   * What each analysis reads. Every column is a name the structure proposal recognises
   * (ROLE_ALIASES) or an input collection_health binds (INPUT_LABELS); a test holds them to it.
   */
  | { kind: 'fields'; rows: FieldRow[] }
  /** Save the three 补充数据模板 to a folder the manager picks. */
  | { kind: 'templates' };

export type FieldRow = {
  analysis: string;
  /** What kind of file or sheet holds it, in a manager's words. */
  files: string;
  columns: string[];
  optional?: string[];
};

export type GuideArticle = {
  id: string;
  section: string;
  title: string;
  /** Where in the window this applies. */
  appliesTo: string;
  /** Words a finance manager would type when looking for it. */
  keywords: string[];
  body: GuideBlock[];
};

